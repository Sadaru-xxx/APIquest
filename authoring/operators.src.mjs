// 正解の位置が偏らないよう、POS で指定された位置へ正解の選択肢を移す(単一選択のみ)
function q(d) {
  if (POS[d.id]) {
    if (d.answer.length !== 1) throw new Error(d.id + ': POS は単一選択のみ');
    const from = LABELS.indexOf(d.answer[0]);
    const to = LABELS.indexOf(POS[d.id]);
    const [o] = d.options.splice(from, 1);
    d.options.splice(to, 0, o);
    const [w] = d.why.splice(from, 1);
    d.why.splice(to, 0, w);
    d.answer = [POS[d.id]];
  }
  const options = d.options.map((o, i) => {
    const label = LABELS[i];
    if (Array.isArray(o)) return { label, text: o[0], claim: o[1] };
    return { label, code: o.code };
  });
  if (d.why.length !== options.length) throw new Error(`${d.id}: why の数が選択肢と一致しない`);
  const whyMap = Object.fromEntries(options.map((o, i) => [o.label, d.why[i]]));
  const isPer = !!d.template;
  return {
    id: d.id,
    pairId: d.id.slice(0, -1),
    side: d.id.slice(-1),
    fieldId: 'operators',
    topicId: d.topic,
    tags: d.tags,
    difficulty: d.diff,
    format: d.template ? 'compile' : 'result',
    prompt: d.prompt,
    files: d.code ? [{ path: 'Main.java', code: d.code }] : [],
    ...(d.command ? { command: d.command } : {}),
    selectCount: d.answer.length,
    options,
    answer: d.answer,
    explanation: { point: d.point, detail: d.detail, options: whyMap },
    ...(NOTES[d.id] ? { variationNote: NOTES[d.id] } : {}),
    refs: refs(...d.refs),
    verify: isPer
      ? { kind: 'per-option', template: d.template, polarity: d.polarity }
      : { kind: 'program' },
  };
}

